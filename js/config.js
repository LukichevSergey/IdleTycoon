/**
 * Множитель дохода от состояния здания.
 * Запущенное здание приносит заметно меньше — стимул чинить вовремя.
 */
function condMult(cond) {
  if (cond >= 70) return 1;
  if (cond >= 40) return 0.8;
  if (cond >= 15) return 0.55;
  return 0.3;
}
